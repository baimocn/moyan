def student_profile(
    level: str = "大学生", weaknesses: list[str] | None = None, recent: str = "",
) -> str:
    w = "、".join(weaknesses or [])
    return f"学段：{level}；薄弱点：{w or '暂无'}；最近表现：{recent or '暂无'}"